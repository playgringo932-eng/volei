// Generate past attendance sessions for realistic testing
export function generateInitialAttendanceSessions(): DailyAttendanceSession[] {
  const sessions: DailyAttendanceSession[] = [];
  const dates = [
    '2026-10-12',
    '2026-10-14',
    '2026-10-16',
    '2026-10-19',
    '2026-10-21',
    '2026-10-23',
    '2026-10-26',
    '2026-10-28',
    '2026-10-29', // Today
  ];

  INITIAL_CLASSES.forEach((cls) => {
    const classStudents = INITIAL_STUDENTS.filter((s) => s.classId === cls.id);
    if (classStudents.length === 0) return;

    dates.forEach((dateStr, idx) => {
      const entries: Record<string, { status: 'presente' | 'falta' | 'justificada' | 'atraso'; note?: string; updatedAt: string }> = {};

      classStudents.forEach((student, sIdx) => {
        // Deterministic simulation
        const hash = (idx * 7 + sIdx * 13) % 20;
        let status: 'presente' | 'falta' | 'justificada' | 'atraso' = 'presente';
        let note: string | undefined = undefined;

        if (hash === 3 || hash === 17) {
          status = 'falta';
        } else if (hash === 9) {
          status = 'justificada';
          note = 'Atestado médico entregue';
        } else if (hash === 14) {
          status = 'atraso';
          note = 'Chegou 15 min após aquecimento';
        }

        entries[student.id] = {
          status,
          note,
          updatedAt: `${dateStr}T${cls.startTime}:00.000Z`,
        };
      });

      sessions.push({
        id: `${cls.id}_${dateStr}`,
        classId: cls.id,
        date: dateStr,
        instructorName: cls.instructorName,
        entries,
        savedAt: `${dateStr}T${cls.endTime}:00.000Z`,
        shift: cls.shift,
      });
    });
  });

  return sessions;
}

